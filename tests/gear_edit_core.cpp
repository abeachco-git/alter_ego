#include "../src/GearEditCore.h"
#include "../src/ComponentGearEditCore.h"
#include <cassert>
#include <cstdint>
#include <map>
struct Slot {
    std::vector<uint32_t> infusion_ids;
    std::vector<std::string> infusion_attributes;
    bool infusion_snapshot = false;
    std::string infusion, sigil, sigil2;
    uint32_t sigil_id = 0, sigil2_id = 0, item_id=0, stat_id=0, rune_id=0;
    std::string stat_name,rune,weapon_type;
};
struct Build {
    std::string name,notes,rune_name,relic_name;
    uint32_t rune_id=0,relic_id=0;
    std::map<std::string,Slot> gear;
    std::vector<uint32_t> infusion_totals;
    bool infusion_summary_present=false;
    int infusion_ar_total=0;
    std::map<std::string,int> infusion_stat_totals;
};
int case_gear_edit_core(int, char**) {
    using namespace AlterEgo::GearEdit;
    Slot src, dst;
    src.infusion_ids = {42}; src.infusion_attributes = {"Power"};
    CopyInfusions(dst, src, InfusionCapacity("Ring1", false));
    assert(dst.infusion_ids == std::vector<uint32_t>({42,42,42}));
    assert(dst.infusion_attributes == std::vector<std::string>({"Power","Power","Power"}));
    src.infusion_ids = {42,43}; src.infusion_attributes = {"","Precision"};
    CopyInfusions(dst, src, 3);
    assert(dst.infusion_ids == std::vector<uint32_t>({42,43,42}));
    CopyInfusions(dst, src, InfusionCapacity("Amulet", false));
    assert(dst.infusion_ids.empty());
    Slot unknown, explicitEmpty;
    dst.infusion_ids={99};dst.infusion_attributes={"Precision"};
    assert(!CopyInfusions(dst,unknown,3,false)&&dst.infusion_ids==std::vector<uint32_t>({99}));
    src.infusion_ids={42,0};src.infusion_attributes={"Power",""};
    assert(CopyInfusions(dst,src,3,false)&&dst.infusion_ids==std::vector<uint32_t>({42}));
    assert(CopyInfusions(dst,src,3,true)&&dst.infusion_ids==std::vector<uint32_t>({42,42,42}));
    explicitEmpty.infusion_snapshot=true;
    assert(CopyInfusions(dst,explicitEmpty,3,false)&&dst.infusion_ids.empty()&&dst.infusion_snapshot);
    Slot parsed;
    assert(!ReadComponentField(GearJson{{"infusion_snapshot",false}},CopyField::Infusions,false,parsed));
    assert(ReadComponentField(GearJson{{"infusion_snapshot",true}},CopyField::Infusions,false,parsed));
    GearJson unknownCapacity={{"item_id",7},{"future",99}};
    assert(ApplyComponentField(unknownCapacity,CopyField::Infusions,false,src,3,false));
    assert(unknownCapacity.at("infusion_ids")==GearJson::array({42})&&unknownCapacity.at("future")==99);
    src.stat_id=1130;src.stat_name="Berserker";src.rune_id=9;src.rune="Scholar";
    CopyStats(dst,src);CopyRune(dst,src);
    assert(dst.stat_id==1130&&dst.stat_name=="Berserker"&&dst.rune_id==9&&dst.rune=="Scholar");
    ClearInfusions(dst);assert(dst.infusion_snapshot&&dst.infusion_ids.empty());
    GearJson partial={{"stat_id",1130},{"stat_name","Berserker"},{"future",42}};
    Slot typed{};assert(ReadComponentField(partial,CopyField::Stats,true,typed));
    GearJson target={{"item_id",7},{"future",99}};
    assert(ApplyComponentField(target,CopyField::Stats,true,typed,1));
    assert(target["stat_id"]==1130&&target["item_id"]==7&&target["future"]==99);
    target["stat_id"]="unknown";
    const auto unchanged=target;
    assert(!ApplyComponentField(target,CopyField::Stats,true,typed,1)&&target==unchanged);
    assert(ComponentOwnsField("aquatic","HelmAquatic",CopyField::Upgrade));
    assert(!ComponentOwnsField("armor","Helm",CopyField::Upgrade));
    Slot removal;
    removal.infusion_ids={11,22,33};
    removal.infusion_attributes={"Power","","Precision"};
    removal.infusion="Legacy infusion";
    assert(RemoveInfusion(removal,1));
    assert(removal.infusion_ids==std::vector<uint32_t>({11,33}));
    assert(removal.infusion_attributes==std::vector<std::string>({"Power","Precision"}));
    assert(removal.infusion_snapshot&&removal.infusion.empty());
    assert(InfusionSelectionAfterRemoval(2,1,2)==1);
    assert(InfusionSelectionAfterRemoval(1,1,2)==1);
    assert(RemoveInfusion(removal,0));
    assert(RemoveInfusion(removal,0));
    assert(removal.infusion_ids.empty()&&removal.infusion_attributes.empty()&&removal.infusion_snapshot);
    assert(InfusionSelectionAfterRemoval(0,0,0)==-1);
    assert(!RemoveInfusion(removal,0));
    Slot exact;exact.infusion_ids={42};
    assert(RemoveInfusion(exact,0)&&exact.infusion_snapshot&&exact.infusion_ids.empty());
    src.sigil_id = 1; src.sigil = "Force";
    CopySigils(dst,src,2); assert(dst.sigil_id == 1 && dst.sigil2_id == 1);
    src.sigil2_id = 2; src.sigil2 = "Accuracy";
    CopySigils(dst,src,2); assert(dst.sigil2_id == 2);
    CopySigils(dst,src,1); assert(dst.sigil2_id == 0);
    assert(InfusionCapacity("WeaponB2",false,true) == 0);
    assert(InfusionCapacity("WeaponB2",true)==1);
    assert(InfusionCapacity("WeaponAquaticA",false)==2);
    assert(ResolveSocketCapacity(3,std::nullopt).limit==3&&!ResolveSocketCapacity(3,std::nullopt).verified);
    assert(ResolveSocketCapacity(3,1).limit==1&&ResolveSocketCapacity(3,1).verified);
    assert(ResolveSocketCapacity(1,3).limit==1);
    assert(ResolveSocketCapacity(0,3).limit==0);
    assert(ResolveSocketCapacity(2,0).limit==0&&ResolveSocketCapacity(2,0).verified);
    assert(SigilCapacity("WeaponA2",true)==1&&SigilCapacity("WeaponA1",true)==2);
    assert(SigilCapacity("WeaponAquaticA",false)==2&&SigilCapacity("Ring1",true)==0);
    assert(!ComponentOwnsField("sigils","Ring1",CopyField::Upgrade));
    assert(!ComponentOwnsField("infusions","HelmAquatic",CopyField::Infusions));
    assert(!ComponentOwnsField("infusions","Amulet",CopyField::Infusions));
    assert(ComponentOwnsField("aquatic","WeaponAquaticA",CopyField::Infusions));
    Slot flexible;flexible.infusion_attributes={"Power","Precision"};flexible.infusion="old";
    assert(InfusionPositionCount(flexible)==2&&InfusionPositionAt(flexible,1).attribute=="Precision");
    assert(SetInfusionPosition(flexible,0,{4294967295u,""}));
    assert(flexible.infusion_ids[0]==4294967295u&&flexible.infusion_attributes[1]=="Precision");
    assert(flexible.infusion_snapshot&&flexible.infusion.empty());
    assert(!AddInfusionPosition(flexible,2));
    assert(AddInfusionPosition(flexible,3)&&InfusionPositionAt(flexible,2).attribute=="Power");
    assert(RemoveInfusion(flexible,1)&&InfusionPositionCount(flexible)==2);
    GearJson data={{"gear",{{"Helm",{{"infusion_ids",GearJson::array({11})},{"extension",42}}},
                              {"Ring1",{{"infusion_snapshot",true}}},{"Ring2",GearJson::object()}}}};
    ClearComponentInfusionSlots(data);
    assert(data["gear"]["Helm"]["extension"]==42&&!data["gear"]["Helm"].contains("infusion_ids"));
    assert(!data["gear"].contains("Ring1")&&data["gear"].contains("Ring2"));
    Slot weapon;
    weapon.weapon_type="Sword";weapon.item_id=42;weapon.sigil2_id=77;weapon.infusion_ids={1,2};
    auto same=AlterEgo::EquipmentChoice::PlanWeaponChange("WeaponA1","Sword","Sword",false);
    ApplyWeaponChange(weapon,"Sword",same);
    assert(weapon.item_id==42&&weapon.sigil2_id==77&&weapon.infusion_ids.size()==2);
    auto changed=AlterEgo::EquipmentChoice::PlanWeaponChange("WeaponA1","Sword","Axe",false);
    ApplyWeaponChange(weapon,"Axe",changed);
    assert(weapon.item_id==0&&weapon.weapon_type=="Axe"&&weapon.sigil2_id==0&&weapon.infusion_ids.size()==1);
    GearJson weapons={{"WeaponA1",{{"weapon_type","Sword"},{"item_id",42},{"future",99}}},
                      {"WeaponA2",{{"weapon_type","Axe"}}},
                      {"WeaponAquaticA",{{"weapon_type","Harpoon"},{"item_id",77}}}};
    const auto original=weapons;
    assert(!ApplyComponentWeaponChange(weapons,"WeaponA1","Sword",false)&&weapons==original);
    assert(!ApplyComponentWeaponChange(weapons,"WeaponA1","Harpoon",true)&&weapons==original);
    assert(ApplyComponentWeaponChange(weapons,"WeaponA1","Greatsword",true));
    assert(!weapons["WeaponA1"].contains("item_id")&&weapons["WeaponA1"]["future"]==99&&!weapons.contains("WeaponA2"));
    assert(!ApplyComponentWeaponChange(weapons,"WeaponAquaticA","Spear",true));
    assert(ApplyComponentWeaponChange(weapons,"WeaponAquaticA","Trident",true)&&weapons.contains("WeaponA1"));
    Build parent;
    assert(!HasRecordedAquaticGear(parent.gear));
    parent.gear["HelmAquatic"].infusion_snapshot=true;
    assert(!HasRecordedAquaticGear(parent.gear));
    parent.gear["WeaponAquaticA"].weapon_type="Harpoon";
    assert(HasRecordedAquaticGear(parent.gear));
    parent.gear.erase("WeaponAquaticA");parent.gear["WeaponAquaticB"].infusion_ids={42};
    assert(HasRecordedAquaticGear(parent.gear));
    auto bulk=BulkSlots(parent.gear);
    assert(std::find(bulk.begin(),bulk.end(),"WeaponAquaticB")!=bulk.end());
    assert(std::find(bulk.begin(),bulk.end(),"HelmAquatic")==bulk.end());
    parent.gear["HelmAquatic"].rune_id=9;
    bulk=BulkSlots(parent.gear);
    assert(std::find(bulk.begin(),bulk.end(),"HelmAquatic")!=bulk.end());
    assert(InfusionCapacity("AquaticA",true)==2);
    parent.name="Loadout";parent.notes="Original";parent.gear["Helm"].infusion_ids={42};
    auto removedChild=parent;
    assert(RemoveInfusion(removedChild.gear.at("Helm"),0));
    assert(parent.gear.at("Helm").infusion_ids==std::vector<uint32_t>({42}));
    auto applied=parent;
    ApplyEquipmentDraft(applied,removedChild);
    assert(applied.gear.at("Helm").infusion_ids.empty()&&applied.gear.at("Helm").infusion_snapshot);
    parent.gear["WeaponA2"].sigil_id=1;
    auto child=parent;child.gear["Helm"].infusion_ids={99};child.gear.erase("WeaponA2");
    child.relic_id=7;child.infusion_ar_total=150;
    // Discarding a child leaves all parent fields intact, including the offhand.
    assert(parent.gear.at("Helm").infusion_ids.front()==42&&parent.gear.count("WeaponA2"));
    assert(parent.relic_id==0);
    parent.notes="New notes";
    ApplyEquipmentDraft(parent,child);
    assert(parent.gear.at("Helm").infusion_ids.front()==99&&!parent.gear.count("WeaponA2"));
    assert(parent.relic_id==7&&parent.infusion_ar_total==150);
    assert(parent.name=="Loadout"&&parent.notes=="New notes");
    return 0;
}
