#include "../src/InfusionTotalsCore.h"
#include <cassert>
using namespace AlterEgo;
int case_infusion_totals(int, char**) {
    assert(AgonyRequirement(162) == 150);
    assert(AgonyRequirement(135) == 135);
    assert(AgonyRequirement(-1) == 0);
    assert(ParseAgonyResistance("+9 Agony Resistance") == 9);
    assert(ParseAgonyResistance("Grants +12 Agony Resistance") == 12);
    assert(ParseAgonyResistance("Agony Infusion +9") == 9);
    assert(ParseAgonyResistance("Power +5") == 0);
    InfusionSummary saved{true, true, 162, {{"Power", 25}, {"Precision", 20}}};
    InfusionSummary live{true, true, 150, {{"Power", 25}, {"Precision", 15}}};
    auto warnings = CompareInfusionTotals(saved, live);
    assert(warnings.size() == 1 && warnings[0].attribute == "Precision");
    live.agonyResistance = 149;
    warnings = CompareInfusionTotals(saved, live);
    assert(warnings.size() == 2 && warnings[0].attribute == "Agony Resistance");
    saved.agonyResistance = 135; live.agonyResistance = 135;
    live.stats["Precision"] = 20;
    assert(CompareInfusionTotals(saved, live).empty());
    saved.present = false;
    assert(CompareInfusionTotals(saved, live).empty());
    saved.present = true; saved.complete = false;
    assert(CompareInfusionTotals(saved, live).empty());
    struct Slot { bool infusion_snapshot=false; std::string infusion,weapon_type;
        uint32_t item_id=0; std::vector<uint32_t> infusion_ids; std::vector<std::string> infusion_attributes; };
    struct Build { bool infusion_summary_present=false; int infusion_ar_total=0;
        std::map<std::string,int> infusion_stat_totals; std::vector<int> infusion_totals;
        std::map<std::string,Slot> gear; };
    Build b;
    assert(GetInfusionMode(b)==InfusionMode::Slots);
    b.gear["Helm"].infusion_ids={123};b.gear["Helm"].item_id=42;
    b.gear["HelmAquatic"].infusion_attributes={"Power"};
    auto before=b;
    b.infusion_summary_present=true;
    assert(GetInfusionMode(b)==InfusionMode::Conflict);
    ForgetAggregateInfusions(b);
    assert(GetInfusionMode(b)==InfusionMode::Slots);
    assert(!SetNumericInfusionTotals(b,{true,false,0,{}}));
    assert(b.gear["Helm"].infusion_ids[0]==123);
    assert(SetNumericInfusionTotals(b,{true,true,9,{{"Power",5}}}));
    assert(GetInfusionMode(b)==InfusionMode::Totals);
    assert(b.gear["Helm"].item_id==42&&b.gear["Helm"].infusion_ids.empty());
    assert(b.gear["HelmAquatic"].infusion_attributes.empty());
    RestoreSlotInfusions(b,before);
    assert(GetInfusionMode(b)==InfusionMode::Slots&&b.gear["Helm"].infusion_ids[0]==123);
    b.gear["Helm"].item_id=43;b.gear.erase("HelmAquatic");
    RestoreSlotInfusions(b,before);
    assert(b.gear["Helm"].infusion_ids.empty()&&!b.gear.count("HelmAquatic"));
    b.infusion_totals={1};b.gear["Helm"].infusion_snapshot=true;
    assert(GetInfusionMode(b)==InfusionMode::Conflict);
    using C=InfusionConfiguration;
    assert(InfusionSlotInConfiguration("Helm",C::LandA));
    assert(!InfusionSlotInConfiguration("Helm",C::WaterA));
    assert(InfusionSlotInConfiguration("HelmAquatic",C::WaterA));
    assert(!InfusionSlotInConfiguration("HelmAquatic",C::LandB));
    assert(InfusionSlotInConfiguration("Ring1",C::WaterB));
    assert(!InfusionSlotInConfiguration("WeaponA1",C::LandB));
    assert(!InfusionSlotInConfiguration("WeaponAquaticA",C::WaterB));
    assert(InfusionSlotInConfiguration("AquaticB",C::WaterB));
    assert(!InfusionSlotInConfiguration("Amulet",C::LandA));
    auto configurations=InfusionConfigurations([](const std::string& slot){
        return slot=="WeaponB1"||slot=="WeaponAquaticB";
    });
    assert((configurations==std::vector<C>{C::LandB,C::WaterB}));
    Build onlyEnrichment;
    onlyEnrichment.gear["Amulet"].infusion_ids={100};
    onlyEnrichment.infusion_summary_present=true;
    assert(GetInfusionMode(onlyEnrichment)==InfusionMode::Totals);
    ForgetSlotInfusions(onlyEnrichment);
    assert(onlyEnrichment.gear["Amulet"].infusion_ids[0]==100);
    Build updated;
    updated.infusion_totals={9};
    assert(!PreserveInfusionModeOnSourceRefresh(before,updated)); // exact local requirements
    assert(!PreserveInfusionModeOnSourceRefresh(b,updated)); // mixed legacy
    Build manual;manual.infusion_summary_present=true;manual.infusion_ar_total=150;
    assert(PreserveInfusionModeOnSourceRefresh(manual,updated));
    assert(updated.infusion_summary_present&&updated.infusion_ar_total==150&&updated.infusion_totals.empty());
    Build imported;imported.infusion_totals={1,2};Build omitted;
    assert(PreserveInfusionModeOnSourceRefresh(imported,omitted)&&omitted.infusion_totals==imported.infusion_totals);
    return 0;
}
